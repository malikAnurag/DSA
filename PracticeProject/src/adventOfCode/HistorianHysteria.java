    private static int calculate(String str) {

        String[] lines = str.split("\n");

        // Arrays to store the separated values
        int[] firstArray = new int[lines.length];
        int[] secondArray = new int[lines.length];

        // Parse each line and populate the arrays
        for (int i = 0; i < lines.length; i++) {
            // Split each line by space to get the two numbers
            String[] numbers = lines[i].split(" ");

            // Convert the strings to integers and store them in the respective arrays
            firstArray[i] = Integer.parseInt(numbers[0]);
            secondArray[i] = Integer.parseInt(numbers[3]);
        }
        return calculateSimilarityScore(firstArray, secondArray);
    }

    private static int calculateSimilarityScore(int[] arr1, int[] arr2) {

        int score = 0;
        Map<Integer, Integer> hm = new HashMap<>();

        for (int j : arr1) {
            hm.put(j, 0);
        }

        for(int k : arr2) {
            if(hm.containsKey(k)) {
                hm.put(k, hm.get(k) + 1);
            }
        }

        System.out.println(hm);

        for(int n : arr1) {
            score += n * hm.get(n);
        }
        return score;
    }

    private static int calculateDistance(int[] arr1, int[] arr2) {

        int sum = 0;
        Arrays.sort(arr1);
        Arrays.sort(arr2);

        for(int i = 0 ; i < arr1.length ; i++) {
            sum+= Math.abs(arr1[i] - arr2[i]);
        }
        return sum;
    }
